 await expect(page.locator(".post-card")).toHaveCount(7);
 const linked=await page.evaluate(async()=>{
  const token=sessionStorage.getItem("sentinelx-token");
  const workspace=(document.querySelector('[aria-label="Active workspace"]') as HTMLSelectElement).value;
  const campaigns=await(await fetch('http://127.0.0.1:18081/api/v1/campaigns?workspace_id='+workspace,{headers:{Authorization:'Bearer '+token}})).json();
  return campaigns[0].mission_id;
 });
 expect(linked).toBe(report.id);
 await nav.getByRole("button",{name:"Business mission",exact:true}).click();
 await expect(page.getByRole("heading",{name:"The opportunity",exact:true})).toBeVisible();
