 expect(report.trace).toHaveLength(4);expect(report.verification).toBeNull();
 await page.screenshot({path:"test-results/business-mission-desktop.png",fullPage:true});
 await page.getByRole("button",{name:"Prepare campaign from mission",exact:true}).click();
